"""The verifier's public finding IDs.

These IDs are the only thing telemetry ever reports about a failed check:
never code, paths, keys or envelopes. Each one's words live in the copy
module as ``finding.<ID>.title``, ``.sent``, ``.why`` and ``.fix`` (a
``.<variant>`` suffix picks a more specific wording where one exists).

Every ID blocks the tutorial from moving on, except the notes in ``NOTES``.
"""

